/*
	Dataset benchmarking metrics, loaded on demand from the shared
	static/data/dataset-benchmarking/results.json (keyed by dataset name), plus optional
	per-dataset UMAP embedding files under static/data/dataset-benchmarking/embeddings/
	(<dataset>_umap.bin, holding both the 2D and 3D projections — see parseEmbeddingBinary below
	for the file format; generated by scripts/convert-embeddings-to-binary.mjs). One task type's
	metric shape is defined below; other task types will get their own shape as their
	benchmarking pipelines ship.
*/
