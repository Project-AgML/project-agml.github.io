// Only image-classification benchmarks exist today; other task types will get their own
// metric shapes later.
export type BenchmarkData = ImageClassificationBenchmark;

type BenchmarkResults = Record<string, BenchmarkData>;

// One row per sample from a UMAP projection. 2D files omit `z`.
export interface EmbedPoint {
	x: number;
	y: number;
	z?: number;
	label: string;
	split?: string;
	index?: number;
}

interface BenchmarkState {
	data: BenchmarkData | null;
	embeddings2d: EmbedPoint[] | null;
	embeddings3d: EmbedPoint[] | null;
	loading: boolean;
}

const EMPTY_STATE: BenchmarkState = {
	data: null,
	embeddings2d: null,
	embeddings3d: null,
	loading: false,
};

async function fetchJson<T>(url: string): Promise<T | null> {
	try {
		const response = await fetch(url);
		if (!response.ok) return null;
		return (await response.json()) as T;
	} catch {
		return null;
	}
}

/*
	Binary layout written by scripts/convert-embeddings-to-binary.mjs (all multi-byte fields
	little-endian). The 2D and 3D UMAP projections for a dataset are independently-fit but
	describe the same samples in the same order, so one file holds both coordinate sets
	sharing a single label/split table and per-point metadata array:
		offset 0   magic "UEB2" (4 ASCII bytes)
		offset 4   uint8  flags (bit0 = has 2D coords, bit1 = has 3D coords)
		offset 5   uint16 labelCount
		offset 7   uint8  splitCount
		offset 8   uint32 pointCount
		label table:  labelCount entries of [uint8 len][len bytes utf8]
		split table:  splitCount entries of [uint8 len][len bytes utf8]
		metadata records (pointCount times, shared by both coordinate sets):
			uint16 labelIdx, uint8 splitIdx, uint32 index
		2D coords (pointCount times, only present if flags bit0 set): float32 x, float32 y
		3D coords (pointCount times, only present if flags bit1 set): float32 x, float32 y, float32 z
*/
const EMBEDDING_MAGIC = "UEB2";
const EMBEDDING_FLAG_2D = 1 << 0;
const EMBEDDING_FLAG_3D = 1 << 1;

interface ParsedEmbeddings {
	embeddings2d: EmbedPoint[] | null;
	embeddings3d: EmbedPoint[] | null;
}

function parseEmbeddingBinary(buffer: ArrayBuffer): ParsedEmbeddings {
	const view = new DataView(buffer);
	const magic = String.fromCharCode(view.getUint8(0), view.getUint8(1), view.getUint8(2), view.getUint8(3));
	if (magic !== EMBEDDING_MAGIC) return { embeddings2d: null, embeddings3d: null };

	let offset = 4;
	const flags = view.getUint8(offset);
	offset += 1;
	const has2d = (flags & EMBEDDING_FLAG_2D) !== 0;
	const has3d = (flags & EMBEDDING_FLAG_3D) !== 0;
	const labelCount = view.getUint16(offset, true);
	offset += 2;
	const splitCount = view.getUint8(offset);
	offset += 1;
	const pointCount = view.getUint32(offset, true);
	offset += 4;

	const decoder = new TextDecoder();
	const labels: string[] = new Array(labelCount);
	for (let i = 0; i < labelCount; i++) {
		const len = view.getUint8(offset);
		offset += 1;
		labels[i] = decoder.decode(new Uint8Array(buffer, offset, len));
		offset += len;
	}
	const splits: string[] = new Array(splitCount);
	for (let i = 0; i < splitCount; i++) {
		const len = view.getUint8(offset);
		offset += 1;
		splits[i] = decoder.decode(new Uint8Array(buffer, offset, len));
		offset += len;
	}

	const labelIdx: Uint16Array = new Uint16Array(pointCount);
	const splitIdx: Uint8Array = new Uint8Array(pointCount);
	const index: Uint32Array = new Uint32Array(pointCount);
	for (let i = 0; i < pointCount; i++) {
		labelIdx[i] = view.getUint16(offset, true);
		offset += 2;
		splitIdx[i] = view.getUint8(offset);
		offset += 1;
		index[i] = view.getUint32(offset, true);
		offset += 4;
	}

	let embeddings2d: EmbedPoint[] | null = null;
	if (has2d) {
		embeddings2d = new Array(pointCount);
		for (let i = 0; i < pointCount; i++) {
			const x = view.getFloat32(offset, true);
			offset += 4;
			const y = view.getFloat32(offset, true);
			offset += 4;
			embeddings2d[i] = { x, y, label: labels[labelIdx[i]], split: splits[splitIdx[i]], index: index[i] };
		}
	}

	let embeddings3d: EmbedPoint[] | null = null;
	if (has3d) {
		embeddings3d = new Array(pointCount);
		for (let i = 0; i < pointCount; i++) {
			const x = view.getFloat32(offset, true);
			offset += 4;
			const y = view.getFloat32(offset, true);
			offset += 4;
			const z = view.getFloat32(offset, true);
			offset += 4;
			embeddings3d[i] = { x, y, z, label: labels[labelIdx[i]], split: splits[splitIdx[i]], index: index[i] };
		}
	}

	return { embeddings2d, embeddings3d };
}

async function fetchEmbeddingBinary(url: string): Promise<ParsedEmbeddings> {
	try {
		const response = await fetch(url);
		if (!response.ok) return { embeddings2d: null, embeddings3d: null };
		return parseEmbeddingBinary(await response.arrayBuffer());
	} catch {
		return { embeddings2d: null, embeddings3d: null };
	}
}

/*
results.json is one shared file covering every dataset, so it only needs to be
fetched once per page load rather than once per dataset looked up.
*/
let resultsPromise: Promise<BenchmarkResults> | null = null;
function loadResults(url: string): Promise<BenchmarkResults> {
	if (!resultsPromise) {
		resultsPromise = fetchJson<BenchmarkResults>(url).then((data) => data ?? {});
	}
	return resultsPromise;
}

/*
	iNatAg and iNatAg-mini are "parent/species" dataset families (e.g. "iNatAg/acacia_neriifolia")
	whose UMAP embedding files live one directory down — embeddings/iNatAg/<species>_umap.bin,
	embeddings/iNatAg-mini/<species>_umap.bin — instead of flat like every other dataset. Any
	other dataset name that happens to contain a "/" (none exist today) is flattened instead of
	being treated as a path, so it can't probe a directory that isn't one of these two known
	families.
*/
const NESTED_EMBEDDING_FAMILIES = ["iNatAg", "iNatAg-mini"];

function embeddingPath(datasetName: string): string {
	const isNestedFamily = NESTED_EMBEDDING_FAMILIES.some((family) => datasetName.startsWith(`${family}/`));
	const base = isNestedFamily ? datasetName : datasetName.replace(/\//g, "_");
	return `/data/dataset-benchmarking/embeddings/${base}_umap.bin`;
}
/*
Looks up `datasetName` in the shared results.json and, if found, fetches that dataset's
combined 2D+3D UMAP embedding file. Returns null data when the dataset has no benchmark
entry (a missing key, not an error state) or when the fetch itself fails.
*/
export function useBenchmark(datasetName: string | null): BenchmarkState {
	const resultsUrl = useBaseUrl("/data/dataset-benchmarking/results.json");
	const embeddingsUrl = useBaseUrl(embeddingPath(datasetName ?? "_none"));
	const [state, setState] = useState<BenchmarkState>(EMPTY_STATE);

	useEffect(() => {
		if (!datasetName) {
			setState(EMPTY_STATE);
			return;
		}
		let cancelled = false;
		setState({ data: null, embeddings2d: null, embeddings3d: null, loading: true });

		loadResults(resultsUrl).then((results) => {
			if (cancelled) return;
			const data = results[datasetName] ?? null;
			if (!data) {
				setState({ data: null, embeddings2d: null, embeddings3d: null, loading: false });
				return;
			}
			fetchEmbeddingBinary(embeddingsUrl).then(({ embeddings2d, embeddings3d }) => {
				if (cancelled) return;
				setState({ data, embeddings2d, embeddings3d, loading: false });
			});
		});

		return () => {
			cancelled = true;
		};
	}, [datasetName, resultsUrl, embeddingsUrl]);

	return state;
}
